class Example:
    def __init__(self, name, title, description, *, world=None, calendars=None, source=None, package_id=None):
        self.name = name
        self.title = title
        self.description = description
        self.world = copy.deepcopy(world or WORLD)
        self.calendars = calendars
        self.source = source
        self.package_id = package_id or f"urn:example:wmi:{name}"
        self.grids: dict = {}
        self.class_tables: dict = {}
        self.layers: list = []
        self.files: dict[str, bytes] = {}
        self.expected: list = []
        self.notes: list = []
        self._arrays: dict = {}

    def grid(self, gid, width, height, west=-180.0, east=180.0, north=90.0, south=-90.0, description=None):
        g = {"type": "lonlat_regular", "width": width, "height": height,
             "bounds": {"west": west, "east": east, "north": north, "south": south}}
        if description:
            g = {"type": "lonlat_regular", "description": description, **{k: v for k, v in g.items() if k != "type"}}
        self.grids[gid] = g
        return mesh(g)

    def class_table(self, tid, taxonomy, classes, title=None, description=None):
        t = {"taxonomy": taxonomy}
        if title:
            t["title"] = title
        if description:
            t["description"] = description
        t["classes"] = classes
        self.class_tables[tid] = t

    def _validity(self, lid, valid, name):
        if valid is None:
            return None
        valid = np.asarray(valid, dtype=bool)
        path = f"masks/{name or lid + '-valid'}.png"
        data = pngmod.write_png(np.where(valid, 255, 0).astype(np.uint8), 8)
        if path in self.files and self.files[path] != data:
            raise ValueError(f"shared validity mask {path} differs")
        self.files[path] = data
        return {"path": path, "sha256": ""}

    def _common(self, layer, title, description, definition, qualifiers, time, source, provenance):
        for key, value in (("title", title), ("description", description), ("definition", definition)):
            if value:
                layer[key] = value
        if qualifiers:
            layer["qualifiers"] = qualifiers
        if time:
            layer["time"] = time
        if source:
            layer["source"] = source
        if provenance:
            layer["provenance"] = provenance

    def scalar(self, lid, quantity, values, units, grid, *, enc=None, valid=None, qualifiers=None, time=None,
               title=None, description=None, definition=None, source=None, provenance=None, validity_name=None,
               statistics=True, samples=None):
        values = np.asarray(values, dtype=np.float64)
        lo, hi = enc if enc else scalarmod.choose_range(values, valid)
        pixels = scalarmod.encode(values, lo, hi, valid)
        path = f"maps/{lid}.png"
        self.files[path] = pngmod.write_png(pixels, 16)
        layer = {"id": lid, "kind": "scalar", "quantity": quantity}
        self._common(layer, title, description, definition, None, None, None, None)
        layer.update({"grid": grid, "path": path, "sha256": "", "units": units,
                      "encoding": {"type": "png16_linear", "min": lo, "max": hi}})
        vm = self._validity(lid, valid, validity_name)
        if vm:
            layer["validity_mask"] = vm
        self._common(layer, None, None, None, qualifiers, time, source, provenance)
        if statistics:
            decoded = scalarmod.decode(pixels, lo, hi)
            stats = scalarmod.statistics(decoded, None if valid is None else np.asarray(valid, bool))
            layer["statistics"] = {k: (round(v, 6) if isinstance(v, float) else v) for k, v in stats.items()}
        self.layers.append(layer)
        self._arrays[lid] = values
        half = scalarmod.quantization_step(lo, hi) / 2
        vmask = np.ones(values.shape, bool) if valid is None else np.asarray(valid, bool)
        for r, c in self._points(values.shape, samples, values, vmask):
            lat, lon = geometry.pixel_centre(self.grids[grid], r, c)
            entry = {"layer": lid, "row": r, "col": c, "lat": round(lat, 6), "lon": round(lon, 6), "valid": bool(vmask[r, c])}
            if vmask[r, c]:
                entry.update({"value": float(values[r, c]), "units": units, "pixel": int(pixels[r, c]), "tolerance": half})
            self.expected.append(entry)

    def categorical(self, lid, quantity, codes, grid, table, *, valid=None, qualifiers=None, time=None, title=None,
                    description=None, source=None, samples=None):
        codes = np.asarray(codes, dtype=np.uint16)
        path = f"maps/{lid}.png"
        self.files[path] = pngmod.write_png(codes, 16)
        layer = {"id": lid, "kind": "categorical", "quantity": quantity}
        self._common(layer, title, description, None, None, None, None, None)
        layer.update({"grid": grid, "path": path, "sha256": "", "encoding": {"type": "png16_codes"}, "class_table": table})
        vm = self._validity(lid, valid, None)
        if vm:
            layer["validity_mask"] = vm
        self._common(layer, None, None, None, qualifiers, time, source, None)
        self.layers.append(layer)
        lookup = {c["code"]: c["id"] for c in self.class_tables.get(table, {"classes": []})["classes"]}
        vmask = np.ones(codes.shape, bool) if valid is None else np.asarray(valid, bool)
        per_class = [tuple(int(x) for x in np.argwhere((codes == k) & vmask)[0]) for k in np.unique(codes[vmask])]
        for r, c in self._points(codes.shape, list(samples or []) + per_class):
            lat, lon = geometry.pixel_centre(self.grids[grid], r, c)
            entry = {"layer": lid, "row": r, "col": c, "lat": round(lat, 6), "lon": round(lon, 6), "valid": bool(vmask[r, c])}
            if vmask[r, c]:
                entry.update({"code": int(codes[r, c]), "class_id": lookup.get(int(codes[r, c]))})
            self.expected.append(entry)

    def mask(self, lid, quantity, truth, grid, *, qualifiers=None, title=None, description=None, samples=None, valid=None):
        truth = np.asarray(truth, dtype=bool)
        path = f"maps/{lid}.png"
        self.files[path] = pngmod.write_png(np.where(truth, 255, 0).astype(np.uint8), 8)
        layer = {"id": lid, "kind": "mask", "quantity": quantity}
        self._common(layer, title, description, None, None, None, None, None)
        layer.update({"grid": grid, "path": path, "sha256": "", "encoding": {"type": "png8_binary"}})
        vm = self._validity(lid, valid, None)
        if vm:
            layer["validity_mask"] = vm
        if qualifiers:
            layer["qualifiers"] = qualifiers
        self.layers.append(layer)
        extra = list(samples or []) + [tuple(int(x) for x in np.argwhere(truth)[0])] if truth.any() else list(samples or [])
        for r, c in self._points(truth.shape, extra):
            lat, lon = geometry.pixel_centre(self.grids[grid], r, c)
            self.expected.append({"layer": lid, "row": r, "col": c, "lat": round(lat, 6), "lon": round(lon, 6),
                                  "valid": True, "mask": bool(truth[r, c])})

    def reference(self, lid, image, role, registration, *, grid=None, depicts=None, title=None, description=None):
        path = f"previews/{lid}.png"
        self.files[path] = pngmod.write_png(image, 8)
        layer = {"id": lid, "kind": "reference"}
        if title:
            layer["title"] = title
        if description:
            layer["description"] = description
        if grid:
            layer["grid"] = grid
        layer.update({"path": path, "sha256": "", "role": role, "registration": registration})
        if depicts:
            layer["depicts"] = depicts
        self.layers.append(layer)

    def raw_layer(self, layer, path, data):
        self.files[path] = data
        self.layers.append(layer)

    @staticmethod
    def _points(shape, extra=None, values=None, valid=None):
        h, w = shape
        pts = [(0, 0), (0, w - 1), (h - 1, 0), (h - 1, w - 1), (h // 2, w // 2), (h // 4, w // 3), (3 * h // 4, 2 * w // 3)]
        if values is not None and valid is not None and valid.any():
            masked = np.where(valid, values, np.nan)
            pts.append(tuple(int(x) for x in np.unravel_index(np.nanargmin(masked), shape)))
            pts.append(tuple(int(x) for x in np.unravel_index(np.nanargmax(masked), shape)))
        pts += list(extra or [])
        seen, out = set(), []
        for p in pts:
            if p not in seen:
                seen.add(p)
                out.append(p)
        return out

    def manifest(self):
        m = {
            "format": "world-map-interchange",
            "format_version": "0.1.0",
            "package": {
                "id": self.package_id,
                "title": self.title,
                "description": self.description,
                "created": CREATED,
                "producer": PRODUCER,
                "license": LICENSE,
                "attribution": ATTRIBUTION,
            },
            "world": self.world,
        }
        if self.source:
            m["source"] = self.source
        if self.calendars:
            m["calendars"] = self.calendars
        m["grids"] = self.grids
        if self.class_tables:
            m["class_tables"] = self.class_tables
        m["layers"] = self.layers
        return m

    def write(self, outdir: Path, *, mutate_before_hash=None, mutate_after_hash=None, sidecars=False, expected=True):
        manifest = copy.deepcopy(self.manifest())
        files = dict(self.files)
        if mutate_before_hash:
            mutate_before_hash(manifest, files)
        for layer in manifest["layers"]:
            if layer.get("path") in files:
                layer["sha256"] = sha256_bytes(files[layer["path"]])
            vm = layer.get("validity_mask")
            if vm and vm["path"] in files:
                vm["sha256"] = sha256_bytes(files[vm["path"]])
        if sidecars:
            for layer in manifest["layers"]:
                if layer["kind"] != "reference":
                    files[layer["path"] + ".json"] = dump_json(sidecar_for(manifest, layer)).encode()
        if mutate_after_hash:
            mutate_after_hash(manifest, files)
        target = outdir / self.name
        target.mkdir(parents=True, exist_ok=True)
        for rel, data in files.items():
            p = target.joinpath(*rel.split("/"))
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
        (target / "manifest.json").write_text(dump_json(manifest), encoding="utf-8", newline="\n")
        if expected:
            doc = {"example": self.name, "title": self.title, "package": f"examples/valid/{self.name}",
                   "notes": self.notes, "samples": self.expected}
            exp_dir = outdir.parent / "expected"
            exp_dir.mkdir(parents=True, exist_ok=True)
            (exp_dir / f"{self.name}.json").write_text(dump_json(doc), encoding="utf-8", newline="\n")
        return target


