def ex_elevation_bathymetry(out):
    ex = Example(
        "elevation-bathymetry",
        "Signed elevation with bathymetry and a known sea level",
        "Full elevation including sea floor, relative to sea level (0 m). Positive-down sea-floor depth, ocean, lake and river masks, "
        "plus a registered colour preview and an unregistered legend.",
        source={"simulation_id": "example-sim-1", "run_id": "run-7", "snapshot_id": "snap-120",
                "simulation_time": {"calendar": "aster", "year": 120, "label": "Year 120 of the example run"},
                "source_heightmap": {"id": "example-heightmap-1", "description": "Analytic heightmap defined in generate_examples.py"}},
        calendars={"aster": ASTER},
    )
    lat, lon = ex.grid("global-128", 128, 64)
    elev = elevation_field(lat, lon)
    ocean = elev < 0
    lake = np.zeros_like(ocean)
    lake[18:21, 70:74] = True
    lake &= ~ocean
    river = np.zeros_like(ocean)
    for c in range(60, 90):
        river[int(round(30 + 6 * np.sin(c / 5.0))), c] = True
    river &= ~ocean & ~lake
    ex.scalar("elevation", "elevation", elev, "m", "global-128", enc=(-8000.0, 6000.0),
              qualifiers={"datum": "sea_level", "coverage": "full", "surface": "top_of_solid_surface", "lake_treatment": "lake_surface"},
              title="Elevation relative to sea level",
              description="Signed: negative values are bathymetry. Encoding range is wider than the observed extrema (see statistics).")
    ex.scalar("sea-floor-depth", "sea_floor_depth", np.where(ocean, -elev, np.nan), "m", "global-128", enc=(0.0, 8000.0),
              valid=ocean, validity_name="ocean-only", title="Sea-floor depth (positive down)")
    ex.mask("ocean", "ocean_mask", ocean, "global-128", qualifiers={"classification": "cell_centre"})
    ex.mask("lakes", "lake_mask", lake, "global-128")
    ex.mask("rivers", "river_mask", river, "global-128", qualifiers={"rasterisation": "Synthetic sinusoidal channel, one cell wide"})
    ex.reference("elevation-preview", hypsometric(elev), "preview", "registered", grid="global-128", depicts=["elevation"],
                 title="Hypsometric colour preview (not numeric data)")
    ex.reference("elevation-legend", colour_bar(), "legend", "unregistered", depicts=["elevation-preview"],
                 title="Colour bar for the preview, -8000 m (left) to 6000 m (right)")
    ex.notes = [
        "Sea level is 0 m (datum 'sea_level'). With encoding -8000..6000 the derived sea-level pixel is "
        f"floor(8000/14000*65535 + 0.5) = {int(scalarmod.encode([0.0], -8000.0, 6000.0)[0])}.",
        "Samples with valid=false in sea-floor-depth are land.",
    ]
    ex.write(out, sidecars=True)


def ex_climate_only(out):
    ex = Example(
        "climate-only",
        "Climate-only export (no height layer)",
        "Temperature statistics and precipitation for a fictional calendar. No elevation layer: a climate-only bundle is valid.",
        calendars={"aster": ASTER},
        source={"simulation_id": "example-climate-sim", "run_id": "clim-run-3",
                "simulation_time": {"calendar": "aster", "year": 30, "label": "End of 30-year climatology"}},
    )
    lat, lon = ex.grid("global-96", 96, 48)
    elev = elevation_field(lat, lon)
    ocean = elev < 0
    tmean, tsea = temperature_mean_c(lat, elev)
    s = np.abs(np.sin(lat))
    trange = (-90.0, 50.0)
    terrain = {"elevation_reference": "terrain", "height_above_surface_m": 2.0}
    ex.scalar("t-annual-mean", "air_temperature", np.round(tmean, 4), "degC", "global-96", enc=trange, qualifiers=terrain,
              time=climatology(ANNUAL_MEAN, "30-year mean of annual means"), title="Annual mean 2 m air temperature")
    ex.scalar("t-annual-min", "air_temperature", np.round(tmean - (8 + 15 * s), 4), "degC", "global-96", enc=trange, qualifiers=terrain,
              time=climatology(MEAN_ANNUAL_MIN, "30-year mean of annual timestep minima"), title="Mean annual minimum (timestep extreme)")
    ex.scalar("t-annual-max", "air_temperature", np.round(tmean + (6 + 10 * s), 4), "degC", "global-96", enc=trange, qualifiers=terrain,
              time=climatology(MEAN_ANNUAL_MAX, "30-year mean of annual timestep maxima"), title="Mean annual maximum (timestep extreme)")
    ex.scalar("t-coldest-period", "air_temperature", np.round(tmean - (4 + 10 * s), 4), "degC", "global-96", enc=trange, qualifiers=terrain,
              time=climatology(COLDEST_PERIOD_MEAN, "Mean temperature of the coldest calendar period"),
              title="Coldest-period mean (extremum of period means)")
    thaw = climatology(ANNUAL_MEAN, "30-year mean of the Thaw period")
    thaw["select_periods"] = ["thaw"]
    ex.scalar("t-thaw-mean", "air_temperature", np.round(tmean - (2 + 6 * s), 4), "degC", "global-96", enc=trange, qualifiers=terrain,
              time=thaw, title="Mean temperature of the Thaw period (single-period climatology)")
    ex.scalar("t-annual-mean-sea-level", "air_temperature", np.round(tsea, 4), "degC", "global-96", enc=trange,
              qualifiers={"elevation_reference": "sea_level_reduced", "height_above_surface_m": 2.0, "lapse_rate_K_per_m": 0.0065},
              time=climatology(ANNUAL_MEAN, "30-year mean of annual means"), title="Annual mean air temperature reduced to sea level")
    sst = np.where(ocean, np.clip(np.round(tsea + 1.0, 4), -1.8, 31.0), np.nan)
    ex.scalar("sst-annual-mean", "sea_surface_temperature", sst, "degC", "global-96", enc=(-2.0, 32.0), valid=ocean,
              validity_name="ocean", time=climatology(ANNUAL_MEAN, "30-year mean of annual means"), title="Annual mean sea-surface temperature")

    total = precipitation_total_mm(lat, lon)
    snow_frac = np.clip((2.0 - tmean) / 12.0, 0.0, 1.0)
    snow = np.round(total * snow_frac, 2)
    rain = np.round(total - snow, 2)
    total = rain + snow
    prange = (0.0, 4000.0)
    t_annual = climatology(ANNUAL_TOTAL, "30-year mean of annual totals")
    ex.scalar("precip-annual", "precipitation_amount", total, "mm", "global-96", enc=prange, time=t_annual,
              title="Mean annual total precipitation (all phases, liquid water equivalent)")
    ex.scalar("rain-annual", "rainfall_amount", rain, "mm", "global-96", enc=prange, time=copy.deepcopy(t_annual),
              title="Mean annual rainfall (liquid only)")
    ex.scalar("snowfall-annual", "snowfall_amount", snow, "mm", "global-96", enc=prange, time=copy.deepcopy(t_annual),
              title="Mean annual snowfall (liquid water equivalent)")
    wettest = np.round(total * (0.30 + 0.15 * np.cos(lon) ** 2), 2)
    ex.scalar("precip-wettest-period", "precipitation_amount", wettest, "mm", "global-96", enc=prange,
              time=climatology(WETTEST_PERIOD_TOTAL, "Mean total of the wettest calendar period"),
              title="Wettest-period precipitation total")
    ex.notes = [
        "Temperatures are in degC and include negative values; the encoding range -90..50 is shared so layers are directly comparable.",
        "rain-annual + snowfall-annual equals precip-annual before quantisation; after decoding they agree within 1.5 quantisation steps.",
        "Where precipitation is exactly 0 mm the sample is valid with pixel 0 (legitimate zero, not missing).",
        "All periods refer to the fictional 'aster' calendar (400 days of 28 h, five unequal periods).",
    ]
    ex.write(out)


def ex_snow_and_soil(out):
    ex = Example(
        "snow-and-soil",
        "Snow and soil moisture with explicit meanings",
        "Snow depth, snow water equivalent, snow-cover fraction, volumetric soil moisture with a declared layer, and a producer-specific model index kept as an extension.",
        calendars={"aster": ASTER},
    )
    lat, lon = ex.grid("global-64", 64, 32)
    elev = elevation_field(lat, lon)
    land = elev >= 0
