def biome_codes(lat, lon, elev):
    ocean = elev < 0
    tmean, tsea = temperature_mean_c(lat, elev)
    p = precipitation_total_mm(lat, lon)
    codes = np.full(elev.shape, 6, dtype=np.uint16)
    codes[ocean & (tsea + 1 < 12)] = 0
    codes[ocean & (tsea + 1 >= 12)] = 1
    land = ~ocean
    codes[land & (tmean < -15)] = 2
    codes[land & (tmean >= -15) & (tmean < -5)] = 3
    codes[land & (tmean >= -5) & (tmean < 3)] = 4
    codes[land & (tmean >= 3) & (tmean < 18) & (p > 700)] = 5
    codes[land & (tmean >= 3) & (p < 250)] = 7
    codes[land & (tmean >= 20) & (p > 1600)] = 8
    return codes


