def mesh(grid):
    lats, lons = geometry.centres(grid, normalize=False)
    lon2, lat2 = np.meshgrid(np.radians(lons), np.radians(lats))
    return lat2, lon2


def elevation_field(lat, lon):
    e = (
        3200 * np.sin(2 * lon + 0.6) * np.cos(lat) ** 0.6
        + 1400 * np.cos(3 * lat) * np.sin(3 * lon - 0.4)
        + 900 * np.sin(5 * lon) * np.sin(4 * lat)
        - 900
    )
    return np.round(e, 3)


def temperature_mean_c(lat, elev):
    sea_level = 27.0 - 52.0 * np.sin(lat) ** 2
    return sea_level - 0.0065 * np.maximum(elev, 0.0), sea_level


def precipitation_total_mm(lat, lon):
    p = 300 + 1900 * np.exp(-((lat / 0.22) ** 2)) + 700 * np.cos(2 * lat) * np.sin(2 * lon + 1.0) - 250 * np.cos(4 * lat)
    return np.maximum(np.round(p, 2), 0.0)


def hypsometric(elev):
    stops = [(-8000, (8, 20, 70)), (-200, (60, 120, 200)), (0, (150, 200, 230)), (1, (60, 140, 70)),
             (1500, (190, 170, 90)), (4000, (140, 110, 90)), (6000, (250, 250, 250))]
    xs = np.array([s[0] for s in stops], dtype=float)
    out = np.zeros(elev.shape + (3,), dtype=np.uint8)
    for ch in range(3):
        ys = np.array([s[1][ch] for s in stops], dtype=float)
        out[..., ch] = np.round(np.interp(elev, xs, ys)).astype(np.uint8)
    return out


def colour_bar(width=256, height=24, alpha=True):
    elev = np.linspace(-8000, 6000, width)[None, :].repeat(height, axis=0)
    rgb = hypsometric(elev)
    if not alpha:
        return rgb
    a = np.full((height, width, 1), 255, dtype=np.uint8)
    a[:, :2] = 0
    a[:, -2:] = 0
    return np.concatenate([rgb, a], axis=2)


def hex_to_rgb(h):
    return tuple(int(h[i : i + 2], 16) for i in (1, 3, 5))


